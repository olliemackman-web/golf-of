// Turns an OpenStreetMap export of a golf course into the data module the game builds holes from:
//   node tools/osm2course.mjs map.osm OLDJOES > src/oldjoesData.js
// It keeps what a hole needs (golf=hole lines, golf=tee, green, pin, fairway, bunker, natural=water)
// and the scenery round it (barrier=hedge, barrier=fence, natural=tree, natural=tree_row,
// natural=scrub, natural=wood or landuse=forest, building=*, highway=unclassified|service, and the
// leisure=golf_course boundary), in metres east and
// north of the middle of the export. Map data © OpenStreetMap contributors, ODbL.
import fs from 'node:fs';

const [file, name = 'COURSE'] = process.argv.slice(2);
if (!file) { console.error('usage: node tools/osm2course.mjs map.osm NAME > out.js'); process.exit(2); }
const xml = fs.readFileSync(file, 'utf8');
const attrs = (s) => Object.fromEntries([...s.matchAll(/(\w[\w:]*)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const tagsOf = (body) => Object.fromEntries([...body.matchAll(/<tag k="([^"]*)" v="([^"]*)"\/>/g)].map((m) => [m[1], m[2]]));

const b = attrs(xml.match(/<bounds [^>]*>/)[0]);
const lat0 = (+b.minlat + +b.maxlat) / 2, lon0 = (+b.minlon + +b.maxlon) / 2, kx = 111320 * Math.cos(lat0 * Math.PI / 180), ky = 110574;
const nodes = new Map();
for (const m of xml.matchAll(/<node ([^>]*?)(\/>|>([\s\S]*?)<\/node>)/g)) { const a = attrs(m[1]); nodes.set(a.id, { p: [+((a.lon - lon0) * kx).toFixed(1), +((a.lat - lat0) * ky).toFixed(1)], tags: m[3] ? tagsOf(m[3]) : {} }); }
const ways = new Map();
for (const m of xml.matchAll(/<way ([^>]*)>([\s\S]*?)<\/way>/g)) ways.set(attrs(m[1]).id, { tags: tagsOf(m[2]), pts: [...m[2].matchAll(/<nd ref="(\d+)"\/>/g)].map((n) => nodes.get(n[1])).filter(Boolean).map((n) => n.p) });

const out = { holes: [], tees: [], greens: [], pins: [], fairways: [], bunkers: [], water: [], hedges: [], fences: [], treeRows: [], trees: [], scrub: [], woods: [], buildings: [], roads: [], boundary: null };
const put = (tags, pts) => {
  const g = tags.golf;
  if (g === 'hole') out.holes.push({ ref: +tags.ref, pts });
  else if (g === 'tee') out.tees.push(pts); else if (g === 'green') out.greens.push(pts); else if (g === 'fairway') out.fairways.push(pts); else if (g === 'bunker') out.bunkers.push(pts);
  else if (tags.natural === 'water') out.water.push(pts); else if (tags.barrier === 'hedge') out.hedges.push(pts); else if (tags.natural === 'scrub') out.scrub.push(pts);
  else if (tags.natural === 'wood' || tags.landuse === 'forest') out.woods.push(pts); else if (tags.barrier === 'fence') out.fences.push(pts); else if (tags.natural === 'tree_row') out.treeRows.push(pts);
  else if (tags.building) out.buildings.push(pts); else if (tags.leisure === 'golf_course') out.boundary = pts;
  else if (tags.highway === 'unclassified' || tags.highway === 'service') out.roads.push({ kind: tags.highway, pts });
};
for (const w of ways.values()) put(w.tags, w.pts);
// multipolygons: the outer ring carries the shape (the inner rings are the greens, tees and bunkers cut out of a fairway)
for (const m of xml.matchAll(/<relation ([^>]*)>([\s\S]*?)<\/relation>/g)) {
  const tags = tagsOf(m[2]); if (tags.type !== 'multipolygon') continue;
  for (const mem of m[2].matchAll(/<member type="way" ref="(\d+)" role="(outer)?"\/>/g)) { const w = ways.get(mem[1]); if (w && mem[2] === 'outer') put(tags, w.pts); }
}
for (const n of nodes.values()) { if (n.tags.golf === 'pin') out.pins.push(n.p); if (n.tags.natural === 'tree') out.trees.push(n.p); }
out.holes.sort((a, b) => a.ref - b.ref);
if (!out.holes.length) { console.error('no golf=hole ways in this export'); process.exit(1); }
// keep only what lies near the course: an export's bounding box drags in long roads and boundaries
const all = out.holes.flatMap((h) => h.pts), x0 = Math.min(...all.map((p) => p[0])) - 150, x1 = Math.max(...all.map((p) => p[0])) + 150, y0 = Math.min(...all.map((p) => p[1])) - 150, y1 = Math.max(...all.map((p) => p[1])) + 150;
const near = (p) => p[0] > x0 && p[0] < x1 && p[1] > y0 && p[1] < y1;
for (const r of out.roads) r.pts = r.pts.filter(near);
out.roads = out.roads.filter((r) => r.pts.length > 1); out.hedges = out.hedges.map((h) => h.filter(near)).filter((h) => h.length > 1);
out.buildings = out.buildings.filter((p) => p.every(near)); out.fences = out.fences.map((h) => h.filter(near)).filter((h) => h.length > 1); out.treeRows = out.treeRows.map((h) => h.filter(near)).filter((h) => h.length > 1);

console.log(`// Generated by tools/osm2course.mjs from an OpenStreetMap export. Do not edit by hand.`);
console.log(`// Map data © OpenStreetMap contributors, available under the Open Database Licence (ODbL).`);
console.log(`// Coordinates are metres east and north of ${lat0.toFixed(5)}, ${lon0.toFixed(5)}.`);
console.log(`export const ${name} = ${JSON.stringify(out)};`);
console.error(`${out.holes.length} holes, ${out.greens.length} greens, ${out.bunkers.length} bunkers, ${out.fairways.length} fairways, ${out.water.length} water, ${out.hedges.length} hedges, ${out.buildings.length} buildings, ${out.roads.length} roads, boundary ${out.boundary ? out.boundary.length + ' points' : 'none'}`);
